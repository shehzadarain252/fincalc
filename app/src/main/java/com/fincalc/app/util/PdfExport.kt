package com.fincalc.app.util

import android.content.Context
import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import android.net.Uri
import androidx.core.content.FileProvider
import java.io.File
import java.io.FileOutputStream

/**
 * Export a calculation result as a PDF (Android PdfDocument, no extra
 * dependency). The file is written to the app cache and shared through
 * FileProvider, so no storage permission is needed.
 */
object PdfExport {

    data class PdfLine(val label: String, val value: String)

    fun export(
        context: Context,
        title: String,
        subtitle: String,
        lines: List<PdfLine>,
        formula: String,
        footer: String = "Generated by FinCalc — Smart Financial Calculators for Everyone. " +
            "Results are estimates for education only, not financial advice."
    ): Uri? {
        return try {
            val doc = PdfDocument()
            val pageWidth = 595 // A4 @ 72dpi
            val pageHeight = 842
            val margin = 48f
            var page = doc.startPage(PdfDocument.PageInfo.Builder(pageWidth, pageHeight, 1).create())
            var canvas = page.canvas
            var y = 72f

            val titlePaint = Paint().apply {
                textSize = 22f; isFakeBoldText = true; color = 0xFF1D4ED8.toInt()
            }
            val subPaint = Paint().apply { textSize = 13f; color = 0xFF6B7280.toInt() }
            val labelPaint = Paint().apply { textSize = 13f; color = 0xFF111827.toInt() }
            val valuePaint = Paint().apply {
                textSize = 13f; isFakeBoldText = true; color = 0xFF111827.toInt()
            }
            val smallPaint = Paint().apply { textSize = 11f; color = 0xFF6B7280.toInt() }
            val linePaint = Paint().apply {
                color = 0xFFE5E7EB.toInt(); strokeWidth = 1f
            }

            fun newPageIfNeeded(needed: Float) {
                if (y + needed > pageHeight - 80) {
                    doc.finishPage(page)
                    page = doc.startPage(
                        PdfDocument.PageInfo.Builder(pageWidth, pageHeight, 1).create()
                    )
                    canvas = page.canvas
                    y = 72f
                }
            }

            canvas.drawText("FinCalc", margin, y, titlePaint); y += 30f
            canvas.drawText(title, margin, y, Paint().apply {
                textSize = 18f; isFakeBoldText = true; color = 0xFF111827.toInt()
            }); y += 26f
            canvas.drawText(subtitle, margin, y, subPaint); y += 24f
            canvas.drawLine(margin, y, pageWidth - margin, y, linePaint); y += 28f

            for (line in lines) {
                newPageIfNeeded(40f)
                canvas.drawText(line.label, margin, y, labelPaint)
                val vWidth = valuePaint.measureText(line.value)
                canvas.drawText(line.value, pageWidth - margin - vWidth, y, valuePaint)
                y += 24f
            }

            if (formula.isNotBlank()) {
                y += 12f
                newPageIfNeeded(60f)
                canvas.drawText("Formula", margin, y, Paint().apply {
                    textSize = 14f; isFakeBoldText = true; color = 0xFF111827.toInt()
                }); y += 22f
                for (part in formula.chunked(72)) {
                    newPageIfNeeded(20f)
                    canvas.drawText(part, margin, y, smallPaint); y += 18f
                }
            }

            y += 24f
            newPageIfNeeded(40f)
            for (part in footer.chunked(72)) {
                newPageIfNeeded(20f)
                canvas.drawText(part, margin, y, smallPaint); y += 18f
            }

            doc.finishPage(page)
            val dir = File(context.cacheDir, "pdfs").apply { mkdirs() }
            val file = File(
                dir,
                "fincalc-${title.lowercase().replace(Regex("[^a-z0-9]+"), "-")}-${System.currentTimeMillis()}.pdf"
            )
            FileOutputStream(file).use { doc.writeTo(it) }
            doc.close()
            FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", file)
        } catch (_: Exception) {
            null
        }
    }
}
